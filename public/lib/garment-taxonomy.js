export const SLOT_BY_KEY = Object.fromEntries(SLOTS.map((slot) => [slot.key, slot]));

/** 目录/导入页的旧分类 → 工作台槽位。 */
export function slotForCategory(category) {
  if (category === 'tops') return 'top';
  if (category === 'bottoms') return 'bottom';
  if (category === 'dresses') return 'dress';
  return 'top';
}

export function subtypesFor(slotKey) {
  return SLOT_BY_KEY[slotKey]?.subtypes ?? [];
}

export function attributesFor(slotKey) {
  return SLOT_BY_KEY[slotKey]?.attributes ?? {};
}

export function defaultSubtype(slotKey) {
  return subtypesFor(slotKey)[0] ?? '';
}
